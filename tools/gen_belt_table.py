#!/usr/bin/env python3
"""Generate pvz2gardendless/belt_table.py: each conveyor level's vanilla score.

    python tools/gen_belt_table.py [--workers 12]

The score is belt_sim.score of the belt as shipped against the vanilla zombies:
the highest zombie-HP scale it still beats. The belt guard (belt_guard.py)
holds a rolled belt against the rolled zombies to that score over
BELT_TOLERANCE. A level scoring 0 is one the simulation cannot judge (its
belt hinges on an effect it does not model) and the guard skips it.

The table records a hash of the inputs it was computed from; belt_guard_test
fails when the simulator or its data changed since.
"""

import argparse
import multiprocessing as mp
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, REPO)
sys.path.insert(0, os.path.join(REPO, "test"))
import apstub  # noqa: E402,F401  (BaseClasses etc. for the package import)

from pvz2gardendless import belt_guard, belt_sim  # noqa: E402

OUT = os.path.join(REPO, "pvz2gardendless", "belt_table.py")


def _score(level):
    return level, round(belt_sim.score(level), 4)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--workers", type=int, default=os.cpu_count() or 1)
    args = ap.parse_args()
    levels = sorted(belt_sim.BELTS)
    t0 = time.time()
    with mp.Pool(args.workers) as pool:
        scores = dict(pool.map(_score, levels))
    zero = sorted(k for k, v in scores.items() if v <= 0)
    lines = ['"""', "PvZ2 Gardendless: each conveyor level's vanilla belt score (belt_guard.py).", "",
             "GENERATED by tools/gen_belt_table.py; do not hand edit.", "",
             f"{len(scores)} levels, {len(zero)} the simulation cannot judge (score 0).",
             '"""', "", "from typing import Dict", "",
             f"INPUT_HASH = {belt_guard.input_hash()!r}", "",
             "BELT_SCORES: Dict[str, float] = {"]
    lines += [f"    {k!r}: {v!r}," for k, v in sorted(scores.items())]
    lines += ["}", ""]
    with open(OUT, "w", encoding="utf8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, REPO)}: {len(scores)} levels, {len(zero)} at 0, "
          f"{time.time() - t0:.0f}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
